// Generates apps/android/.../ui/i18n/PracticeCopy.kt from packages/shared practiceCopy (single source of truth).
// Run after `npm run build -w packages/shared`: node packages/shared/scripts/gen-android-practice-copy.mjs
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const { PRACTICE_COPY } = require(join(here, '../dist/practiceCopy.js'));
const { PROMO_COPY } = require(join(here, '../dist/promoCopy.js'));
const out = join(here, '../../../apps/android/app/src/main/java/app/gotcha/android/ui/i18n/PracticeCopy.kt');
const KOTLIN_KEYWORDS = new Set(['continue', 'break', 'return', 'object', 'class', 'fun', 'val', 'var', 'when', 'is', 'in', 'interface', 'typealias', 'package', 'as', 'do', 'if', 'else', 'for', 'while', 'try', 'throw', 'null', 'true', 'false', 'super', 'this']);
const kid = (k) => (KOTLIN_KEYWORDS.has(k) ? '`' + k + '`' : k);

const kstr = (s) => '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$').replace(/\n/g, '\\n') + '"';
// Functions become format patterns: args → %1$s, %2$s …
const fmt = (fn) => fn(...Array.from({ length: fn.length }, (_, i) => `\u0000${i + 1}`)).replace(/\u0000(\d)/g, (_, d) => `%${d}$s`);
// One-arg counters that inflect (BUG-08): emit "one|||few|||many" and let PracticeCopy.f pick the form.
const counted = (fn) => {
  const at = (n) => fn(n).replace(new RegExp(`(^|\\D)${n}(?=\\D|$)`), `$1%1$s`);
  const forms = [at(1), at(2), at(5)];
  return forms[0] === forms[1] && forms[1] === forms[2] ? forms[0] : forms.join('|||');
};
const keys = Object.keys(PRACTICE_COPY.en);
function emit(lang) {
  const c = PRACTICE_COPY[lang];
  const lines = keys.map((k) => {
    const v = c[k];
    if (typeof v === 'function') return `    ${kid(k)} = ${kstr(v.length === 1 && /^(dueNow|newWords|streakDays|freezes|dueTomorrow|xpToday)$/.test(k) ? counted(v) : fmt(v))},`;
    if (typeof v === 'object') return `    ${kid(k)} = mapOf(${Object.entries(v).map(([a, b]) => `${kstr(a)} to ${kstr(b)}`).join(', ')}),`;
    return `    ${kid(k)} = ${kstr(v)},`;
  });
  const p = PROMO_COPY[lang];
  lines.push(`    promoLabel = ${kstr(p.label)},`, `    promoApply = ${kstr(p.apply)},`, `    lang = ${kstr(lang)},`);
  return `val PRACTICE_${lang.toUpperCase()} = PracticeCopy(\n${lines.join('\n')}\n)`;
}
const fields = keys.map((k) => {
  const v = PRACTICE_COPY.en[k];
  return `    val ${kid(k)}: ${typeof v === 'object' ? 'Map<String, String>' : 'String'},${typeof v === 'function' ? ' // format pattern' : ''}`;
});
fields.push('    val promoLabel: String,', '    val promoApply: String,', '    val lang: String = "en",');
const src = `// GENERATED by packages/shared/scripts/gen-android-practice-copy.mjs from packages/shared/src/practiceCopy.ts.
// Do not edit by hand: change the shared copy and re-run the generator.
package app.gotcha.android.ui.i18n

data class PracticeCopy(
${fields.join('\n')}
) {
    fun f(pattern: String, vararg args: Any): String {
        val forms = pattern.split("|||")
        if (forms.size == 3) {
            val n = (args.firstOrNull() as? Number)?.toLong() ?: 0L
            val idx = when (lang) {
                "ru" -> { val a = Math.abs(n) % 100; val b = a % 10; if (a in 11..14) 2 else if (b == 1L) 0 else if (b in 2..4) 1 else 2 }
                "uz" -> 2
                else -> if (Math.abs(n) == 1L) 0 else 2
            }
            return String.format(forms[idx], *args)
        }
        return String.format(pattern, *args)
    }
}

${['en', 'ru', 'uz'].map(emit).join('\n\n')}

fun practiceCopyFor(lang: String?): PracticeCopy = when (lang?.take(2)) {
    "ru" -> PRACTICE_RU
    "uz" -> PRACTICE_UZ
    else -> PRACTICE_EN
}
`;
writeFileSync(out, src);
console.log('wrote', out, keys.length, 'keys');
