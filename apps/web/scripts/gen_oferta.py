#!/usr/bin/env python3
"""payments-02 (G1): copy PM's canonical oferta AND terms HTML into src/lib/ofertaHtml.generated.ts.
PM 31 Oct: in payments-02 both /oferta and /terms render pending-payments-02 (web/ is the pre-payments text).

Usage: python3 scripts/gen_oferta.py <team/pm/legal/web/pending-payments-02>
Source: pending-payments-02/{oferta,terms}-{uz,ru,en}.html (the payments-02 text: no fixed Plus lookup cap,
speed protection). HTML comments are stripped; check-legal.mjs fails if any survive.
"""
import re, sys, json, pathlib
src = pathlib.Path(sys.argv[1]); here = pathlib.Path(__file__).resolve().parent.parent
docs = {}
for doc in ('oferta', 'terms'):
    out = docs[doc] = {}
    for lang in ('uz', 'ru', 'en'):
        html = (src / f'{doc}-{lang}.html').read_text(encoding='utf8')
        html = re.sub(r'<!--.*?-->', '', html, flags=re.S).strip()
        assert '<!--' not in html, (doc, lang)
        out[lang] = html
ts = '// GENERATED by scripts/gen_oferta.py from team/pm/legal/web/pending-payments-02 (comments stripped). Do not edit.\n'
for doc in docs:
    ts += f"export const {doc.upper()}_HTML: Record<'uz' | 'ru' | 'en', string> = " + json.dumps(docs[doc], ensure_ascii=False, indent=1) + ';\n'
out = {f'{d}.{l}': len(v) for d in docs for l, v in docs[d].items()}
(here / 'src/lib/ofertaHtml.generated.ts').write_text(ts, encoding='utf8')
print('legal generated:', out)
