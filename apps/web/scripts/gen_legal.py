#!/usr/bin/env python3
"""landing-premium-02: embed PM's canonical legal HTML (team/pm/legal/web/{privacy,terms,oferta}-{uz,ru,en}.html,
built by PM's build_html.py from the .md sources) VERBATIM. No text edits here.

Usage: python3 scripts/gen_legal.py <path-to-team/pm/legal/web>
Copies the .html files to legal-src/ and writes src/lib/legalHtml.generated.ts. Fails if an HTML comment survives.
"""
import sys, json, pathlib, shutil
src = pathlib.Path(sys.argv[1]); here = pathlib.Path(__file__).resolve().parent.parent
out = {}
for lang in ('uz', 'ru', 'en'):
    out[lang] = {}
    for doc in ('privacy', 'terms', 'oferta'):
        f = src / f'{doc}-{lang}.html'
        html = f.read_text(encoding='utf8')
        assert '<!--' not in html and '-->' not in html, f'HTML comment in {f.name}'
        shutil.copyfile(f, here / 'legal-src' / f.name)
        out[lang][doc] = html
ts = ('// GENERATED by scripts/gen_legal.py from PM\'s canonical legal HTML (verbatim). Do not edit.\n'
      '// [EFFECTIVE DATE] is still open: a production build fails until it is filled (scripts/legal-guard.mjs).\n'
      'export const LEGAL_HTML_V2: Record<\'uz\' | \'ru\' | \'en\', { privacy: string; terms: string; oferta: string }> = '
      + json.dumps(out, ensure_ascii=False, indent=1) + ';\n')
(here / 'src/lib/legalHtml.generated.ts').write_text(ts, encoding='utf8')
print('legal generated:', {l: {d: len(h) for d, h in v.items()} for l, v in out.items()})
