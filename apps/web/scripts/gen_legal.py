#!/usr/bin/env python3
"""web-launch-02: build the legal pages from PM's drafts (team/pm/legal/web/*.md).

Usage: python3 scripts/gen_legal.py <path-to-team/pm/legal/web>

1. Strips EVERY HTML comment (they hold lawyer/owner notes) before anything else.
2. Writes the stripped markdown to legal-src/ (so no lawyer note ever enters the repo).
3. Renders it to HTML and writes src/lib/legalHtml.generated.ts.
check-legal.mjs then fails the build if '<!--' or any note marker survives.
"""
import re, sys, json, pathlib, markdown
src = pathlib.Path(sys.argv[1]); here = pathlib.Path(__file__).resolve().parent.parent
COMMENT = re.compile(r'<!--.*?-->', re.S)
SELLER = re.compile(r'\[(SELLER[^\]]*|STIR[^\]]*|INN[^\]]*|BANK[^\]]*|LEGAL ADDRESS[^\]]*)\]')
out = {}
for lang in ('uz', 'ru', 'en'):
    out[lang] = {}
    for doc in ('terms', 'privacy', 'oferta'):
        md = (src / f'{doc}-{lang}.md').read_text(encoding='utf8')
        md = COMMENT.sub('', md)
        assert '<!--' not in md and '-->' not in md, f'unclosed comment in {doc}-{lang}.md'
        md = md.replace('[TTS RETENTION]', '30 days' if lang == 'en' else ('30 kun' if lang == 'uz' else '30 дней'))
        md = md.replace('DRAFT, NOT PUBLISHED. ', '')  # PM draft tag; the page shows its own QA banner
        md = md.replace('[OFERTA URL]', 'https://gotchaa.uz/oferta')
        # Seller fields hide while empty: drop any line still holding a seller placeholder.
        md = '\n'.join(l for l in md.split('\n') if not SELLER.search(l))
        md = re.sub(r'\n{3,}', '\n\n', md).strip() + '\n'
        (here / 'legal-src' / f'{doc}-{lang}.md').write_text(md, encoding='utf8')
        html = markdown.markdown(md, extensions=['tables', 'sane_lists'])
        html = re.sub(r'\[(EFFECTIVE DATE|CLAIM PERIOD|TTS RETENTION[^\]]*)\]', r'<mark class="placeholder">[\1]</mark>', html)
        out[lang][doc] = html
ts = ('// GENERATED by scripts/gen_legal.py from PM drafts (comments stripped). Do not edit.\n'
      '// NOT FOR DEPLOY: needs the lawyer review and the owner\'s go (REVIEW-web-launch-02.md).\n'
      'export const LEGAL_HTML_V2: Record<\'uz\' | \'ru\' | \'en\', { terms: string; privacy: string; oferta: string }> = '
      + json.dumps(out, ensure_ascii=False, indent=1) + ';\n')
(here / 'src/lib/legalHtml.generated.ts').write_text(ts, encoding='utf8')
print('legal v2 generated:', {l: {d: len(h) for d, h in v.items()} for l, v in out.items()})
