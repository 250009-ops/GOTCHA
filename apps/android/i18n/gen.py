import json,glob,os,re
# Usage: python3 apps/android/i18n/gen.py  (paths resolve relative to this file)
HERE=os.path.dirname(os.path.abspath(__file__))
R=os.path.join(HERE,'..','app','src','main','res')
import importlib.util
reg={}; plurals={}
for f in sorted(glob.glob(os.path.join(HERE,'*.py'))):
    if f.endswith('gen.py'): continue
    spec=importlib.util.spec_from_file_location(os.path.basename(f)[:-3],f); m=importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
    for k,(en,ru,uz) in getattr(m,'S',{}).items():
        if k in reg: print('DUP',k,f)
        reg[k]={'en':en,'ru':ru,'uz':uz}
    for k,(en,ru,uz) in getattr(m,'P',{}).items():
        plurals[k]={'en':en,'ru':ru,'uz':uz}
for f in sorted(glob.glob(os.path.join(HERE,'reg_*.json'))):
    d=json.load(open(f))
    for k in d:
        if k in reg and reg[k]!=d[k]: print('DUP CONFLICT',k,f)
    reg.update(d)
def esc(v):
    v=v.replace('\\$','$')  # kotlin escapes
    v=v.replace('&','&amp;').replace('<','&lt;').replace('>','&gt;')
    v=v.replace("\\'","'").replace("'","\\'").replace('"','\\"')
    if v.startswith('@') or v.startswith('?'): v='\\'+v
    return v
base={'app_name':'GOTCHA','open_with_gotcha':{'en':'Read in GOTCHA','ru':'Читать в GOTCHA','uz':'GOTCHA’da o‘qish'}}
for lang,d in (('en','values'),('ru','values-ru'),('uz','values-uz')):
    os.makedirs(f'{R}/{d}',exist_ok=True)
    L=['<?xml version="1.0" encoding="utf-8"?>','<!-- GENERATED by apps/android/i18n/gen.py (P3, UI-17). en / ru / uz must stay key-aligned. -->','<resources>']
    if lang=='en': L.append('    <string name="app_name" translatable="false">GOTCHA</string>')
    L.append(f'    <string name="open_with_gotcha">{esc(base["open_with_gotcha"][lang])}</string>')
    for k in sorted(reg):
        v=reg[k][lang]
        fmt=' formatted="false"' if re.search(r'%(?!\d\$)',v) and '%%' not in v else ''
        L.append(f'    <string name="{k}"{fmt}>{esc(v)}</string>')
    for k in sorted(plurals):
        L.append(f'    <plurals name="{k}">')
        for q,v in plurals[k][lang].items():
            L.append(f'        <item quantity="{q}">{esc(v)}</item>')
        L.append('    </plurals>')
    L.append('</resources>')
    out=f'{R}/{d}/strings.xml'
    eol='\r\n' if os.path.exists(out) and b'\r\n' in open(out,'rb').read() else '\n'  # keep the file's line endings
    open(out,'w',newline='').write(eol.join(L)+eol)
print(len(reg),'keys')
